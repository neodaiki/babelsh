"""Generate the bash/zsh hook. `ush init bash > ~/.config/ush/hook.bash`, then source it.

Design (see SPEC §9):
  * command_not_found handler: the shell already split the line and expanded $vars, so the
    handler receives one simple command as argv. `&&`, pipes and redirects keep working
    because the shell handles them; ush only sees the command that was not found.
  * A `sudo` wrapper, because `sudo apt ...` never reaches the handler (sudo reports the error).
  * Wrappers for dialect-sensitive tools (sed) that only call ush when a dialect flag (-i) is
    present; every other call goes straight to `command sed` with no Python.
The file is generated, not static, so the command lists always match the compiled rules.
"""

COMMON = r"""# ush shell hook ({shell}) -- generated by `ush init {shell}`; do not edit.
# Source it from ~/.{shell}rc. Disable temporarily with USH_DISABLE=1.
[ -n "${{_USH_LOADED:-}}" ] && return 0
case $- in *i*) ;; *) [ -n "${{USH_FORCE:-}}" ] || return 0 ;; esac
_USH_LOADED=1
_ush_cmds=' {cmds} '
_ush_always=' {always} '

_ush_run() {{ {launcher} exec -- "$@"; }}
"""

BASH = r"""
_ush_have() {{ type -P -- "$1" >/dev/null 2>&1; }}

if declare -F command_not_found_handle >/dev/null 2>&1; then
  _ush_def="$(declare -f command_not_found_handle)"
  eval "_ush_prev_cnf${{_ush_def#command_not_found_handle}}"
  unset _ush_def
fi
command_not_found_handle() {{
  if [ -z "${{USH_DISABLE:-}}" ]; then
    case "$_ush_cmds" in *" $1 "*) _ush_run "$@"; return $? ;; esac
  fi
  if declare -F _ush_prev_cnf >/dev/null 2>&1; then _ush_prev_cnf "$@"; return $?; fi
  printf '%s: %s: command not found\n' "${{0##*/}}" "$1" >&2
  return 127
}}
"""

ZSH = r"""
_ush_have() {{ whence -p -- "$1" >/dev/null 2>&1; }}

if (( $+functions[command_not_found_handler] )); then
  functions -c command_not_found_handler _ush_prev_cnf
fi
command_not_found_handler() {{
  if [ -z "${{USH_DISABLE:-}}" ]; then
    case "$_ush_cmds" in *" $1 "*) _ush_run "$@"; return $? ;; esac
  fi
  if (( $+functions[_ush_prev_cnf] )); then _ush_prev_cnf "$@"; return $?; fi
  print -u2 "zsh: command not found: $1"
  return 127
}}
"""

SUDO = r"""
sudo() {{
  case "$1" in -*|"") command sudo "$@"; return $? ;; esac
  if [ -z "${{USH_DISABLE:-}}" ]; then
    case "$_ush_cmds" in
      *" $1 "*)
        if ! _ush_have "$1"; then _ush_run sudo "$@"; return $?; fi
        case "$_ush_always" in *" $1 "*) _ush_run sudo "$@"; return $? ;; esac ;;
    esac
  fi
  command sudo "$@"
}}
"""

WRAPPER = r"""
{name}() {{
  if [ -z "${{USH_DISABLE:-}}" ]; then
    local _ush_a
    for _ush_a in "$@"; do
      case $_ush_a in {patterns}) _ush_run {name} "$@"; return $? ;; esac
    done
  fi
  command {name} "$@"
}}
"""


import shlex  # noqa: E402


def dialect_wrappers(rules):
    """{tool: [glob patterns]} for commands whose forms are selected by dialect."""
    flags = {}
    for _intent, form in rules.forms:
        if "dialect" not in form["when"]:
            continue
        m = form["match"]
        for cmd in m["cmd"]:
            bucket = flags.setdefault(cmd, set())
            for key in ("flags_all", "flags_any", "takes_value"):
                for f in m.get(key, []):
                    bucket.add(f + "*")
    return {cmd: sorted(pats) for cmd, pats in flags.items()}


def generate(shell, rules, launcher):
    """`launcher` is the argv that starts ush, e.g. [python, '/repo/bin/ush'] or
    [python, '-m', 'babelsh']; it is shell-quoted into the generated file."""
    if shell not in ("bash", "zsh"):
        raise ValueError("unsupported shell %r (bash and zsh only)" % shell)
    wrappers = dialect_wrappers(rules)
    cmds = sorted(rules.cmds)
    always = sorted(set(wrappers) | {"brew"})
    out = [COMMON.format(shell=shell, launcher=" ".join(shlex.quote(a) for a in launcher),
                         cmds=" ".join(cmds), always=" ".join(always))]
    out.append(BASH.format() if shell == "bash" else ZSH.format())
    out.append(SUDO.format())
    for name in sorted(wrappers):
        out.append(WRAPPER.format(name=name, patterns="|".join(wrappers[name])))
    return "".join(out)
